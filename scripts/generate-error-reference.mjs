// Generate the error-code reference from domain/errors.js so the catalog, the
// recovery metadata (`retryable` / `nextAction`) and the docs cannot disagree
// (#46, #74). Usage: node scripts/generate-error-reference.mjs [--check]
//
// Two artifacts come from the same catalog:
//   - docs/reference/errors.generated.md — the compact generated catalog;
//   - the table block inside docs/reference/errors.md, delimited by
//     `generated:error-table:start/end` markers. The surrounding prose is
//     hand-written; only the table is generated.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { ERROR_CODES } from '../domain/errors.js'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const generatedTarget = path.join(root, 'docs', 'reference', 'errors.generated.md')
const referenceTarget = path.join(root, 'docs', 'reference', 'errors.md')
const START = '<!-- generated:error-table:start -->'
const END = '<!-- generated:error-table:end -->'

const cell = (value) => String(value ?? '').replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim()
const retryableCell = (entry) => (entry.retryable === true ? 'yes' : 'no')
const nextActionCell = (entry) => (entry.nextAction === null || entry.nextAction === undefined ? '—' : cell(entry.nextAction))

/** @param {{ withTrigger?: boolean }} options */
function table(options = {}) {
  const withTrigger = options.withTrigger === true
  const header = withTrigger
    ? '| Code | Meaning | Retryable | Next action | Typical trigger |'
    : '| Code | Meaning | Retryable | Next action |'
  const divider = withTrigger ? '|---|---|---|---|---|' : '|---|---|---|---|'
  const rows = Object.entries(ERROR_CODES).map(([code, entry]) => {
    const base = `| \`${code}\` | ${cell(entry.description)} | ${retryableCell(entry)} | ${nextActionCell(entry)} |`
    return withTrigger ? `${base} ${cell(entry.trigger)} |` : base
  })
  return [header, divider, ...rows].join('\n')
}

const expectedGenerated = `# Error code catalog (generated)

> Generated by \`npm run docs:generate:errors\` from \`domain/errors.js\`. Do not edit by hand.

The catalog is the source of truth for the stable codes and the recovery metadata the tool boundary
renders: \`retryable\` marks a failure that can succeed later unchanged, and \`nextAction\` is the
single recovery step appended to the message as \` — next: …\` (with \` (retryable)\` when retryable).

${table()}
`

/** Replace the marked block in the hand-written reference. @param {string} text */
function expectedReference(text) {
  const start = text.indexOf(START)
  const end = text.indexOf(END)
  if (start === -1 || end === -1 || end < start) {
    throw new Error(`docs/reference/errors.md is missing the ${START} / ${END} markers`)
  }
  return `${text.slice(0, start + START.length)}\n${table({ withTrigger: true })}\n${text.slice(end)}`
}

const referenceSource = fs.readFileSync(referenceTarget, 'utf8')
const expectedReferenceText = expectedReference(referenceSource)

if (process.argv.includes('--check')) {
  const actualGenerated = fs.existsSync(generatedTarget) ? fs.readFileSync(generatedTarget, 'utf8') : ''
  if (actualGenerated !== expectedGenerated) {
    console.error('error reference is stale; run npm run docs:generate:errors')
    process.exit(1)
  }
  if (referenceSource !== expectedReferenceText) {
    console.error('docs/reference/errors.md generated table is stale; run npm run docs:generate:errors')
    process.exit(1)
  }
  const withRecovery = Object.values(ERROR_CODES).filter((entry) => entry.nextAction !== null).length
  console.log(`error reference: ${Object.keys(ERROR_CODES).length} codes in sync (${withRecovery} with a next action)`)
} else {
  fs.mkdirSync(path.dirname(generatedTarget), { recursive: true })
  fs.writeFileSync(generatedTarget, expectedGenerated)
  fs.writeFileSync(referenceTarget, expectedReferenceText)
  const withRecovery = Object.values(ERROR_CODES).filter((entry) => entry.nextAction !== null).length
  console.log(
    `wrote ${path.relative(root, generatedTarget)} and the generated table in ${path.relative(root, referenceTarget)} (${Object.keys(ERROR_CODES).length} codes, ${withRecovery} with a next action)`,
  )
}
