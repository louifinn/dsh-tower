// Generate the error-code reference from domain/errors.js so the catalog and docs
// cannot disagree (#46). Usage: node scripts/generate-error-reference.mjs [--check]
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { ERROR_CODES } from '../domain/errors.js'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const target = path.join(root, 'docs', 'reference', 'errors.generated.md')
const expected = `# Error code catalog (generated)

> Generated by \`npm run docs:generate:errors\` from \`domain/errors.js\`. Do not edit by hand.

| Code | Description |
|---|---|
${Object.entries(ERROR_CODES).map(([code, description]) => `| \`${code}\` | ${description} |`).join('\n')}
`
if (process.argv.includes('--check')) {
  const actual = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : ''
  if (actual !== expected) {
    console.error(`error reference is stale; run npm run docs:generate:errors`)
    process.exit(1)
  }
  console.log(`error reference: ${Object.keys(ERROR_CODES).length} codes in sync`)
} else {
  fs.mkdirSync(path.dirname(target), { recursive: true })
  fs.writeFileSync(target, expected)
  console.log(`wrote ${path.relative(root, target)} (${Object.keys(ERROR_CODES).length} codes)`)
}
