#!/usr/bin/env node
// Generate domain/generated/deny-surface.js — the per-owner tool inventory the
// Tower-mode deny set derives from (#161 D1).
//
//   node scripts/generate-deny-surface.mjs            # write the inventory
//   node scripts/generate-deny-surface.mjs --check    # fail when it is stale
//
// The enumeration imports the pinned upstream owner packages (devDependencies)
// through scripts/lib/owner-surface.mjs; the committed module is what the
// runtime reads, and tests/deny-surface.test.mjs re-enumerates at test time so
// an upstream addition breaks CI rather than leaking past the guard.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { enumerateDenyOwnerTools } from './lib/owner-surface.mjs'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const OUT_FILE = path.join(ROOT, 'domain', 'generated', 'deny-surface.js')

/** @param {Record<string, string[]>} owners */
function render(owners) {
  const header = [
    '// Generated by scripts/generate-deny-surface.mjs — DO NOT EDIT.',
    '//',
    '// Every tool each foreign-orchestration owner registers, enumerated from the',
    '// pinned upstream packages in devDependencies (see scripts/lib/owner-surface.mjs).',
    '// domain/deny-owners.js derives the Tower-mode deny set from this table;',
    '// regenerate with `npm run deny:generate` after bumping the owner pins.',
  ].join('\n')
  return `${header}\n/** @type {Record<string, string[]>} */\nexport const DENY_OWNER_TOOLS = ${JSON.stringify(owners, null, 2)}\n`
}

async function main() {
  const owners = await enumerateDenyOwnerTools()
  const text = render(owners)
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(OUT_FILE) ? fs.readFileSync(OUT_FILE, 'utf8') : null
    if (current !== text) {
      console.error(
        'deny-surface: domain/generated/deny-surface.js is stale; run `npm run deny:generate` and commit the result',
      )
      process.exit(1)
    }
    const total = Object.values(owners).reduce((sum, names) => sum + names.length, 0)
    console.log(`deny-surface: ok (${Object.keys(owners).length} owners, ${total} tool registrations)`)
    return
  }
  fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true })
  fs.writeFileSync(OUT_FILE, text)
  console.log(`deny-surface: wrote ${path.relative(ROOT, OUT_FILE)}`)
}

main().catch((error) => {
  console.error(`deny-surface: ${String(error?.message ?? error)}`)
  process.exit(1)
})
