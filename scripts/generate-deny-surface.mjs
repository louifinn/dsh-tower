#!/usr/bin/env node
// Generate domain/generated/deny-surface.js — the per-owner tool inventory the
// Tower-mode deny set derives from (#161 D1).
//
//   node scripts/generate-deny-surface.mjs            # write the inventory
//   node scripts/generate-deny-surface.mjs --check    # fail when it is stale
//
// The enumeration imports the pinned upstream owner packages (devDependencies)
// through scripts/lib/owner-surface.mjs; the committed module is what the
// runtime reads, and tests/deny-surface.test.mjs re-enumerates at test time so
// an upstream addition breaks CI rather than leaking past the guard.
//
// #190: the generated header records the build the inventory was enumerated
// from and the supported host pin in scripts/support.json, and --check also
// runs evaluateDenyInventoryBuild(). Bumping scripts/support.json without
// reviewing domain/deny-owners.js and regenerating therefore fails deny:check,
// not just a header-only diff.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import {
  DENY_OWNER_PACKAGE_BUILD,
  DENY_INVENTORY_REVIEWED_PIN,
  evaluateDenyInventoryBuild,
} from '../domain/deny-owners.js'
import { enumerateDenyOwnerTools } from './lib/owner-surface.mjs'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const OUT_FILE = path.join(ROOT, 'domain', 'generated', 'deny-surface.js')
const SUPPORT_FILE = path.join(ROOT, 'scripts', 'support.json')
const PACKAGE_FILE = path.join(ROOT, 'package.json')

const GENERATE_HINT = '`npm run deny:generate`'

/** @param {string} file */
function readJson(file) {
  return JSON.parse(fs.readFileSync(file, 'utf8'))
}

/**
 * Render the committed module, recording both builds in the header so a
 * support-pin bump alone makes the file stale (#190).
 *
 * @param {Record<string, string[]>} owners
 * @param {{ supportedBuild: string, inventoryBuild: string }} builds
 */
export function renderDenySurface(owners, { supportedBuild, inventoryBuild }) {
  const header = [
    '// Generated by scripts/generate-deny-surface.mjs — DO NOT EDIT.',
    '//',
    '// Every tool each foreign-orchestration owner registers, enumerated from the',
    '// pinned upstream packages in devDependencies (see scripts/lib/owner-surface.mjs).',
    `// Inventory build: ${inventoryBuild} (domain/deny-owners.js DENY_OWNER_PACKAGE_BUILD)`,
    `// Supported host pin: ${supportedBuild} (scripts/support.json)`,
    '// A support-pin bump alone changes this header, so `npm run deny:check` fails until',
    '// `npm run deny:generate` runs and every per-owner exception has been reviewed.',
  ].join('\n')
  return `${header}\n/** @type {Record<string, string[]>} */\nexport const DENY_OWNER_TOOLS = ${JSON.stringify(owners, null, 2)}\n`
}

/**
 * Enumerate the owners and check the recorded build against the supported host
 * pin and the owner devDependency pins (#190).
 *
 * @param {string} [root]
 * @returns {Promise<{
 *   owners: Record<string, string[]>,
 *   text: string,
 *   supportedBuild: string,
 *   inventoryBuild: string,
 *   evaluation: ReturnType<typeof evaluateDenyInventoryBuild>,
 * }>}
 */
export async function denySurfaceState(root = ROOT) {
  const support = readJson(path.join(root, 'scripts', 'support.json'))
  const packageJson = readJson(path.join(root, 'package.json'))
  const owners = await enumerateDenyOwnerTools()
  const supportedBuild = String(support.dsh ?? '')
  const evaluation = evaluateDenyInventoryBuild({
    supportedBuild,
    devDependencies: packageJson.devDependencies ?? {},
  })
  const text = renderDenySurface(owners, {
    supportedBuild,
    inventoryBuild: DENY_OWNER_PACKAGE_BUILD,
  })
  return { owners, text, supportedBuild, inventoryBuild: DENY_OWNER_PACKAGE_BUILD, evaluation }
}

/**
 * Read-only check: the recorded build must agree with the supported host pin
 * (or a documented per-owner exception), and the committed module must equal
 * the render.
 *
 * @param {string} [root]
 */
export async function denySurfaceCheck(root = ROOT) {
  const state = await denySurfaceState(root)
  const outFile = path.join(root, 'domain', 'generated', 'deny-surface.js')
  const current = fs.existsSync(outFile) ? fs.readFileSync(outFile, 'utf8') : null
  const problems = [...state.evaluation.problems]
  if (current !== state.text) {
    problems.push(
      `domain/generated/deny-surface.js is stale (inventory build ${state.inventoryBuild}, supported host pin ${state.supportedBuild}); run ${GENERATE_HINT} and commit the result`,
    )
  }
  return { ok: problems.length === 0, problems, state, current }
}

async function main() {
  const check = process.argv.includes('--check')
  if (!check) {
    const state = await denySurfaceState()
    if (!state.evaluation.ok) {
      for (const problem of state.evaluation.problems) console.error(`deny-surface: ${problem}`)
      console.error(
        `deny-surface: refusing to write while the recorded build ${DENY_OWNER_PACKAGE_BUILD} does not match the supported host pin and documented exceptions (reviewed pin ${DENY_INVENTORY_REVIEWED_PIN}); run ${GENERATE_HINT} after fixing the pins and exceptions`,
      )
      process.exit(1)
    }
    fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true })
    fs.writeFileSync(OUT_FILE, state.text)
    console.log(`deny-surface: wrote ${path.relative(ROOT, OUT_FILE)}`)
    return
  }
  const result = await denySurfaceCheck()
  if (!result.ok) {
    for (const problem of result.problems) console.error(`deny-surface: ${problem}`)
    process.exit(1)
  }
  const total = Object.values(result.state.owners).reduce((sum, names) => sum + names.length, 0)
  console.log(
    `deny-surface: ok (${Object.keys(result.state.owners).length} owners, ${total} tool registrations)`,
  )
}

function isMain() {
  const entry = process.argv[1]
  return Boolean(entry) && path.resolve(entry) === path.resolve(fileURLToPath(import.meta.url))
}

if (isMain()) {
  main().catch((error) => {
    console.error(`deny-surface: ${String(error?.message ?? error)}`)
    process.exit(1)
  })
}
