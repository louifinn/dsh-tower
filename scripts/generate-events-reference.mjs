// Generate docs/reference/events.md from the event table (#75) so event names
// and payloads cannot drift from the runtime. Usage:
//   node scripts/generate-events-reference.mjs [--check]
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import {
  EVENT_COUNT,
  LEGACY_TOOL_EVENT_TABLE,
  MISSION_EVENT_TABLE,
} from '../domain/events.js'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const target = path.join(root, 'docs', 'reference', 'events.md')

const payloadCell = (entry) => `\`{ ${entry.payload.join(', ')} }\``
const missionRows = MISSION_EVENT_TABLE.map(
  (entry) => `| \`${entry.name}\` | ${payloadCell(entry)} | ${entry.description} |`,
).join('\n')
const legacyRows = LEGACY_TOOL_EVENT_TABLE.map((entry) => `| \`${entry.name}\` | ${entry.description} |`).join('\n')

const expected = `# Tower events

> Generated by \`npm run docs:generate:events\` from \`domain/events.js\`. Do not edit by hand.

Tower emits process-local Cordis events after successful tool calls (mutations and read-only tools), so
other plugins can observe a repository without polling. This release defines ${EVENT_COUNT} process-local events:
${MISSION_EVENT_TABLE.length} stable domain events and ${LEGACY_TOOL_EVENT_TABLE.length} deprecated tool-shaped
aliases. Events are **not** sent over the network and carry no telemetry.

## Domain events (stable)

Domain events describe what changed, not which tool ran. They are emitted only after the state write
succeeds, so \`revision\` is the revision a reader can load back from \`state.json\`; a failed tool emits
no domain event. \`at\` is the transition timestamp in epoch milliseconds. \`state.json\` stays
authoritative: these events are an observation channel, not an event-sourced log, and are never
replayed.

| Event | Payload | Emitted after |
|---|---|---|
${missionRows}

\`\`\`js
ctx.on('tower.mission.merged', ({ missionId, revision, at, commit }) => {
  // the merge is already durable; commit is the merge commit that landed
})
\`\`\`

## Tool-shaped aliases (deprecated)

The older \`tower/<tool>\` events are kept for one minor release as a **deprecated** alias for the
tool-shaped observation channel; prefer the domain events above and expect the alias to be removed in
the next minor. They carry \`{ tool, repoRoot, value }\`, fire after a successful tool call, and never
fail a tool when a listener throws. For \`tower_merge\` the alias also fires for a gate failure whose
\`value.ok\` is false.

| Event | Emitted after |
|---|---|
${legacyRows}

\`\`\`js
ctx.on('tower/merge', (payload) => {
  // deprecated: prefer tower.mission.merged
  // payload.tool, payload.repoRoot, payload.value (the tool's JSON result)
})
\`\`\`

For a durable audit trail use \`<git-common-dir>/dsh-tower/activity.jsonl\` and \`MISSIONS.md\` instead;
events are process-local and are not replayed.
`

if (process.argv.includes('--check')) {
  const actual = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : ''
  if (actual !== expected) {
    console.error('events reference is stale; run npm run docs:generate:events')
    process.exit(1)
  }
  console.log(`events reference: ${EVENT_COUNT} events in sync`)
} else {
  fs.mkdirSync(path.dirname(target), { recursive: true })
  fs.writeFileSync(target, expected)
  console.log(`wrote ${path.relative(root, target)} (${EVENT_COUNT} events)`)
}
