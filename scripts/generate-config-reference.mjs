// Generate the config reference from the schemastery schema (#46).
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { Config, configSurface, resolveTowerConfig } from '../domain/config/schema.js'
import { SURFACE_BASELINE_FILE, surfaceLine } from '../domain/surface.js'
import { readBaseline } from './lib/surface.mjs'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const target = path.join(root, 'docs', 'reference', 'config.generated.md')
const defaults = resolveTowerConfig({})
const baseline = readBaseline(root)
const surface = configSurface()
const rows = []
for (const [key, schema] of Object.entries(Config.dict ?? {})) {
  const dict = schema?.dict
  if (dict && typeof dict === 'object') {
    for (const [child, childSchema] of Object.entries(dict)) {
      rows.push(format(`${key}.${child}`, childSchema, schema))
    }
  } else {
    rows.push(format(key, schema, Config))
  }
}
function format(key, schema, parent) {
  const value = key.split('.').reduce((current, part) => (current == null ? undefined : current[part]), defaults)
  const fallback = value === undefined ? '' : JSON.stringify(value)
  const description = String(schema?.meta?.description ?? parent?.meta?.description ?? '').replace(/\s+/g, ' ').trim()
  return `| \`${key}\` | \`${fallback}\` | ${description} |`
}
// The counts are live for the config half and come from the committed baseline
// for the tools half; `npm run surface:check` makes the two agree, so the header
// is a generated decision record rather than hand-maintained prose.
const counts = {
  configKeys: rows.length,
  sections: surface.sections.length,
  tools: baseline.surfaces.tools.value,
}
const expected = `# Config reference (generated)

> Generated by \`npm run docs:generate:config\` from \`domain/config/schema.js\`. Values are defaults before repo config.
> Surface: ${surfaceLine(counts)} · baseline ${baseline.date}. Generated from \`${SURFACE_BASELINE_FILE}\`; do not edit by hand.

| Key | Default | Description |
|---|---|---|
${rows.join('\n')}
`
if (process.argv.includes('--check')) {
  const actual = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : ''
  if (actual !== expected) {
    console.error('config reference is stale; run npm run docs:generate:config')
    process.exit(1)
  }
  console.log(`config reference: ${rows.length} keys in sync`)
} else {
  fs.mkdirSync(path.dirname(target), { recursive: true })
  fs.writeFileSync(target, expected)
  console.log(`wrote ${path.relative(root, target)} (${rows.length} keys)`)
}
