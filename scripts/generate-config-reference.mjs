// Generate the config reference from the schemastery schema (#46, #M64).
//
// The schema is the single source: the key list, the header counts and the
// default column all come from `domain/config/schema.js`. This script renders;
// `scripts/check-config-reference.mjs` is the gate (drift, missing/duplicated
// rows, stale defaults, hand-maintained key tables) and is what
// `npm run docs:check:generated:config` runs. `--check` here is a byte-compare
// convenience for local use after editing the schema.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { Config, configSurface, resolveTowerConfig } from '../domain/config/schema.js'
import { SURFACE_BASELINE_FILE, surfaceLine } from '../domain/surface.js'
import { readBaseline } from './lib/surface.mjs'

export const CONFIG_REFERENCE_FILE = 'docs/reference/config.generated.md'

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')

/**
 * Render the table rows from the schema. Exported so the gate and the tests can
 * compare the row set and defaults without parsing the generated page.
 *
 * @param {any} [config] the Schemastery root
 * @param {Record<string, any>} [defaults] resolved defaults for the default column
 * @returns {{ key: string, value: string, description: string }[]}
 */
export function configReferenceRows(config = Config, defaults = resolveTowerConfig({})) {
  const rows = []
  for (const [key, schema] of Object.entries(config?.dict ?? {})) {
    const dict = schema?.dict
    if (dict && typeof dict === 'object') {
      for (const [child, childSchema] of Object.entries(dict)) {
        rows.push(format(`${key}.${child}`, childSchema, schema, defaults))
      }
    } else {
      rows.push(format(key, schema, config, defaults))
    }
  }
  return rows
}

function format(key, schema, parent, defaults) {
  const value = key.split('.').reduce((current, part) => (current == null ? undefined : current[part]), defaults)
  const fallback = value === undefined ? '' : JSON.stringify(value)
  const description = String(schema?.meta?.description ?? parent?.meta?.description ?? '').replace(/\s+/g, ' ').trim()
  return { key, value: fallback, description }
}

/**
 * Render the whole generated page. Deterministic for a given schema and
 * baseline file: the tests render twice and compare with the checked-in page.
 *
 * @param {{ root?: string }} [options]
 * @returns {string}
 */
export function renderConfigReference({ root = repoRoot } = {}) {
  const baseline = readBaseline(root)
  const surface = configSurface()
  const rows = configReferenceRows()
  // The counts are live for the config half and come from the committed
  // baseline for the tools half; `npm run surface:check` makes the two agree, so
  // the header is a generated decision record rather than hand-maintained prose.
  const counts = {
    configKeys: surface.count,
    sections: surface.sections.length,
    tools: baseline.surfaces.tools.value,
  }
  return `# Config reference (generated)

> Generated by \`npm run docs:generate:config\` from \`domain/config/schema.js\`. Values are defaults before repo config.
> Surface: ${surfaceLine(counts)} · baseline ${baseline.date}. Generated from \`${SURFACE_BASELINE_FILE}\`; do not edit by hand.

| Key | Default | Description |
|---|---|---|
${rows.map((row) => `| \`${row.key}\` | \`${row.value}\` | ${row.description} |`).join('\n')}
`
}

const isMain = process.argv[1] !== undefined && pathToFileURL(path.resolve(process.argv[1])).href === import.meta.url

if (isMain) {
  const target = path.join(repoRoot, CONFIG_REFERENCE_FILE)
  if (process.argv.includes('--check')) {
    const actual = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : ''
    if (actual !== renderConfigReference({ root: repoRoot })) {
      console.error('config reference is stale; run npm run docs:generate:config')
      process.exit(1)
    }
    console.log(`config reference: ${configSurface().count} keys in sync`)
  } else {
    fs.mkdirSync(path.dirname(target), { recursive: true })
    fs.writeFileSync(target, renderConfigReference({ root: repoRoot }))
    console.log(`wrote ${CONFIG_REFERENCE_FILE} (${configSurface().count} keys)`)
  }
}
