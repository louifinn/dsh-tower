// Generate the shape reference from the one shape registry (#149).
//
// Every fact in docs/reference/shapes.md comes from domain/shapes/index.js and
// the two shape modules, so documentation cannot drift from the policy the
// generic layers actually resolve. `--check` is wired into `npm run check`.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { SHAPE_KINDS, shapeFor } from '../domain/shapes/index.js'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const target = path.join(root, 'docs', 'reference', 'shapes.md')

const rows = SHAPE_KINDS.map((kind) => {
  const shape = shapeFor(kind)
  const hasTerminal = shape.statuses.some((status) => shape.isTerminal(status))
  // #148 W2: a shape with a sandbox dimension resolves its placement from
  // tuning config, so the reference names both placements instead of the static
  // default only.
  const provisioning = shape.fields.sandbox ? '`shared` | `detached`' : `\`${shape.provisioning}\``
  return `| \`${kind}\` | \`${shape.statuses.join('`, `')}\` | ${hasTerminal ? 'yes' : 'no'} | ${provisioning} | ${shape.canMerge} | ${shape.canRebase} | ${shape.ownsScope} | ${shape.requiredComponent ?? '—'} | ${shape.acceptsResult} |`
})

const transitions = SHAPE_KINDS.map((kind) => {
  const shape = shapeFor(kind)
  const body = shape.statuses
    .map((status) => {
      const targets = shape.transitions[status] ?? []
      return `| \`${status}\` | ${shape.isTerminal(status) ? 'terminal' : targets.map((target) => `\`${target}\``).join(', ') || '—'} |`
    })
    .join('\n')
  return `### ${kind}\n\n| From | To |\n|---|---|\n${body}`
})

const invariants = SHAPE_KINDS.map((kind) => {
  const { completion } = shapeFor(kind)
  const flags = Object.entries(completion)
    .filter(([key]) => key.startsWith('requires'))
    .map(([key, value]) => `${key}=${value}`)
    .join(', ')
  return `| \`${kind}\` | ${flags} | \`${completion.check.name}\` |`
})

const expected = `# Mission shapes (generated)

> Generated by \`npm run docs:generate:shapes\` from \`domain/shapes/index.js\`. Do not edit by hand.

A mission shape is the single place its kind's contract lives (#148/#149). Generic
layers resolve \`shapeFor(mission.kind)\` and never branch on a kind literal; the
shape audit (\`npm run shape:audit\`) refuses kind and role comparisons outside
\`domain/shapes/\`, the global \`TERMINAL_STATUSES\`/\`TRANSITIONS\` vocabulary, and
one-argument \`isTerminal\`/\`canTransition\` calls.

## Kinds

| Kind | Statuses | Has terminal | Provisioning | Can merge | Can rebase | Owns scope | Component | Accepts result |
|---|---|---|---|---|---|---|---|---|
${rows.join('\n')}

## Transitions

${transitions.join('\n\n')}

## Survey placement (#148 W2)

\`survey.sandbox\` is tuning, not a component: the \`tower-survey\` row stays the
switch. The shape resolves both the placement and the preset, so generic layers
never read the raw key or compare a kind.

The decision is made once, at provisioning time. A mission with a recorded
\`mission.sandbox\` keeps the detached placement and its completion invariants
even if \`survey.sandbox\` later changes — a config flip can neither skip the
sandbox HEAD/zero-commit checks nor strand the disposable checkout. A survey
that never got a sandbox keeps the shared invariants for the same reason.

| \`survey.sandbox\` | Provisioning | Preset | Completion invariants |
|---|---|---|---|
| \`none\` (default) | \`shared\`: no checkout, the agent reads the main checkout | \`tower-survey\` (strictly read-only: no write, edit, or shell tool) | HEAD equals \`readCommit\`, tracked-status fingerprint unchanged, zero commits |
| \`detached\` | \`detached\`: \`git worktree add --detach <worktreeRoot>/<id>-sandbox <readCommit>\` (no branch, no \`baseCommit\`, never merged) | \`tower-survey-sandbox\` (read/write/edit/pwsh plus the mission tools; spawn/merge/rebase/review/diff still absent) | sandbox HEAD equals \`readCommit\`, zero commits; disposable write/shell side effects are ignored; sandbox removed on completion, abandon or teardown with a bounded retry |

## Completion invariants

| Kind | Invariants | Check |
|---|---|---|
${invariants.join('\n')}

## Role

| Contract | Owner |
|---|---|
| Status, transitions, terminality, merge/rebase, provisioning, plan fields, completion, dependencies, briefing, summary | \`domain/shapes/<kind>.js\` |
| Kind resolution and the action guard | \`domain/shapes/index.js\` |
| Role vocabulary | \`domain/roles.js\` |
| Generated reference and the audit | \`scripts/generate-shapes-reference.mjs\`, \`scripts/shape-audit.mjs\` |

## Dimensions audited

| Dimension | Contract | Fitness rule |
|---|---|---|
| Mission lifecycle | \`shape.statuses\`, \`shape.transitions\`, \`shape.isTerminal\` | No kind literal outside \`domain/shapes/\`; no global terminal set. |
| Role | \`domain/roles.js\` predicates | No role literal outside \`domain/roles.js\`. |
| Provisioning | \`shape.provisioning\` / \`shape.resolveProvisioning\` | Only a build shape may create a worktree/branch; a survey reads in the shared checkout by default or in a disposable detached sandbox when \`survey.sandbox: 'detached'\`. A recorded \`mission.sandbox\` is authoritative once provisioning has happened. |
| Read-only | Preset allow-list plus \`shape.resolveCompletion\` | A shared survey completes with HEAD unchanged, the tracked-status set unchanged, and zero commits; a detached survey may dirty its sandbox but must keep its HEAD pinned and make zero commits. Invariants follow the recorded sandbox, not current config. |
| Dependency | \`shape.dependencySatisfied\` | A completed survey satisfies a dependent build; a merged build satisfies it too. |
| Archive / reanchor / planning | \`shape.isTerminal\` | A terminal shape leaves open work and does not block reanchor; terminal surveys archive. |
| Evidence | \`shape.acceptsResult\` | Only a survey may record a completion result. |
| Component | \`shape.requiredComponent\` | Planning refuses with an actionable code while the required component is off. |

## Suspected dimensions: verdicts

| Dimension | Verdict | Fitness rule |
|---|---|---|
| Review | A review is a verdict on a build branch tip, not a mission shape. The reviewer reads the worker worktree, so review requires \`shape.fields.worktree\`. | A survey is never reviewed (\`canMerge=false\` refuses \`tower_review\`'s branch prerequisite). |
| Batch | A batch is finite evidence over build missions; it has its own open/closed/abandoned lifecycle and is not a mission shape. | A survey has no worktree/branch requirement and completes with zero commits; a batch never changes mission terminality. |
| Leases | Leases are advisory coordination, never authority. | Spawn prechecks read the lease component; the shape does not. |
| Paused vs blocked | Both are non-terminal statuses whose targets come from the shape table. | \`shape.transitions.paused\` and \`shape.transitions.blocked\` are the only source. |
| Test receipts | A discovery receipt belongs to a build branch tip; a survey has no branch and no tree tip. | \`shape.fields.worktree=false\` skips mission discovery. |
| Legacy import | A legacy import is read-only data; the v3→v4 migration stamps every mission with a shape and converts a branch-shaped survey into \`readCommit\`/\`readDirty\`. | \`shape.migrateLegacy\` is the only v3→v4 mission rewrite. |
| Scope ownership | Only a shape that writes owns a scope. | \`shape.ownsScope=false\` forces an empty scope and skips scope fences and auto-deps. |
| Role vs kind | Roles describe actors; shapes describe missions. They are separate vocabularies. | \`domain/roles.js\` owns roles; \`domain/shapes/\` owns kinds. |
`

if (process.argv.includes('--check')) {
  const actual = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : ''
  if (actual !== expected) {
    console.error('shapes reference is stale; run npm run docs:generate:shapes')
    process.exit(1)
  }
  console.log(`shapes reference: ${SHAPE_KINDS.length} shapes in sync`)
} else {
  fs.mkdirSync(path.dirname(target), { recursive: true })
  fs.writeFileSync(target, expected)
  console.log(`wrote ${path.relative(root, target)} (${SHAPE_KINDS.length} shapes)`)
}
process.exit(0)
