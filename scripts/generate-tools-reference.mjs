// Generate the tools overview from the registered tool definitions (#46).
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { registerTowerTools } from '../tools/index.js'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const target = path.join(root, 'docs', 'reference', 'tools.generated.md')
const tools = new Map()
const ctx = {
  get() {
    return undefined
  },
  effect(fn) {
    const dispose = fn()
    return typeof dispose === 'function' ? dispose : () => {}
  },
  systemPrompt: { section() {} },
  tools: {
    register(definition) {
      tools.set(definition.name, definition)
      return () => {}
    },
    guard() {
      return () => {}
    },
    restrict() {
      return () => {}
    },
  },
}
registerTowerTools(ctx)
const rows = [...tools.values()]
  .sort((a, b) => a.name.localeCompare(b.name))
  .map((tool) => `| \`${tool.name}\` | ${String(tool.description ?? '').replace(/\s+/g, ' ').trim()} |`)
const expected = `# Tools overview (generated)

> Generated by \`npm run docs:generate:tools\` from the registered tool definitions. Do not edit by hand.

| Tool | Description |
|---|---|
${rows.join('\n')}
`
if (process.argv.includes('--check')) {
  const actual = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : ''
  if (actual !== expected) {
    console.error('tools reference is stale; run npm run docs:generate:tools')
    process.exit(1)
  }
  console.log(`tools reference: ${tools.size} tools in sync`)
} else {
  fs.mkdirSync(path.dirname(target), { recursive: true })
  fs.writeFileSync(target, expected)
  console.log(`wrote ${path.relative(root, target)} (${tools.size} tools)`)
}
process.exit(0)
