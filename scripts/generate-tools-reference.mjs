// Generate the tools overview from the registered tool definitions (#46).
//
// #118: use the shipped Host entry, not only the define() path, so the table and
// its header count include tower_mode/tower_control as well.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { SURFACE_BASELINE_FILE, surfaceLine } from '../domain/surface.js'
import { loadShippedToolSurface } from './lib/tool-surface.mjs'
import { readBaseline } from './lib/surface.mjs'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const target = path.join(root, 'docs', 'reference', 'tools.generated.md')
const baseline = readBaseline(root)
const surface = loadShippedToolSurface()
const tools = surface.definitions
const rows = [...tools.values()]
  .sort((a, b) => a.name.localeCompare(b.name))
  .map((tool) => `| \`${tool.name}\` | ${String(tool.description ?? '').replace(/\s+/g, ' ').trim()} |`)
// Live tools count, baseline config counts: `npm run surface:check` keeps the
// two halves equal, so the generated header carries one decision record.
const counts = {
  configKeys: baseline.surfaces.configKeys.value,
  sections: baseline.surfaces.sections.value,
  tools: tools.size,
}
const expected = `# Tools overview (generated)

> Generated by \`npm run docs:generate:tools\` from the registered tool definitions. Do not edit by hand.
> Surface: ${surfaceLine(counts)} · baseline ${baseline.date}. Generated from \`${SURFACE_BASELINE_FILE}\`; do not edit by hand.

| Tool | Description |
|---|---|
${rows.join('\n')}
`
surface.dispose()
if (process.argv.includes('--check')) {
  const actual = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : ''
  if (actual !== expected) {
    console.error('tools reference is stale; run npm run docs:generate:tools')
    process.exit(1)
  }
  console.log(`tools reference: ${tools.size} tools in sync`)
} else {
  fs.mkdirSync(path.dirname(target), { recursive: true })
  fs.writeFileSync(target, expected)
  console.log(`wrote ${path.relative(root, target)} (${tools.size} tools)`)
}
process.exit(0)
