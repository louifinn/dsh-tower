// Generate the blocker/failure reference (English and Chinese) from
// domain/shapes/blockers.js (#M62 W2-A) so the registry is the only place a
// code, its section, or its recovery prose is written. Usage:
//   node scripts/generate-blockers-reference.mjs [--check] [--root <dir>]
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { BLOCKER_DEFINITIONS } from '../domain/shapes/blockers.js'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const TARGETS = ['docs/reference/blockers.md', 'docs/zh/reference/blockers.md']

const cell = (value) => String(value ?? '').replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim()
const list = (codes) => codes.map((code) => `\`${code}\``).join(', ')

/**
 * @param {ReadonlyArray<{ code: string, kinds: string[], summary: { en: string, zh: string }, reviewOnly?: boolean, warningByDefault?: boolean }>} entries
 * @returns {{ gate: any[], merge: any[], rebase: any[], shared: any[], review: any[], warning: any[] }}
 */
function sections(entries) {
  const gate = entries.filter((entry) => entry.kinds.includes('gate'))
  const merge = entries.filter((entry) => entry.kinds.includes('merge'))
  const rebase = entries.filter((entry) => entry.kinds.includes('rebase'))
  return {
    gate,
    merge,
    rebase,
    shared: entries.filter((entry) => entry.kinds.length > 1),
    review: entries.filter((entry) => entry.reviewOnly === true),
    warning: entries.filter((entry) => entry.warningByDefault === true),
  }
}

/** @param {any[]} entries @param {'en' | 'zh'} locale */
function table(entries, locale) {
  const header = locale === 'zh' ? '| Code | 含义 / 下一步 |' : '| Code | Meaning / next action |'
  return [header, '|---|---|', ...entries.map((entry) => `| \`${entry.code}\` | ${cell(entry.summary[locale])} |`)].join('\n')
}

/**
 * The full reference text for both locales. Pure: no filesystem access, so
 * tests can mutate the entry list and prove the generated text follows it.
 * @param {ReadonlyArray<any>} entries
 * @returns {{ en: string, zh: string }}
 */
export function renderBlockersReference(entries = BLOCKER_DEFINITIONS) {
  const { gate, merge, rebase, shared, review, warning } = sections(entries)
  // Shared codes (`worker-busy`) are listed last in the rebase section so the
  // rebase-only failures read first, matching the gate table's declaration order.
  const rebaseRows = [...rebase].sort((a, b) => Number(a.kinds.length > 1) - Number(b.kinds.length > 1))
  const total = entries.length
  const mergeOnly = merge.filter((entry) => !entry.kinds.includes('gate')).length
  const rebaseOnly = rebase.filter((entry) => !entry.kinds.includes('gate')).length
  const sharedNames = list(shared.map((entry) => entry.code))
  const rebaseHeading = shared.length === 0 ? `Rebase failures (${rebase.length})` : `Rebase failures (${rebase.length}; ${sharedNames} shared)`
  const zhRebaseHeading =
    shared.length === 0 ? `rebase 失败（${rebase.length} 个）` : `rebase 失败（${rebase.length} 个；${sharedNames} 与门禁共用）`
  const sharedFooter = shared.length === 0 ? '' : `；${sharedNames} 与门禁共用`
  const reviewNames = list(review.map((entry) => entry.code))
  const warningNames = list(warning.map((entry) => entry.code))

  const enSurvey =
    warning.length === 0
      ? ''
      : `${warningNames} is special: it is reported as a stable warning in \`plan\`/\`preflight\` by default and
becomes a merge blocker only when \`gates.requireFreshSurvey\` is \`true\`. Its warning object carries
\`{code, missionId, depId, readCommit, baseCommit, message}\` so a caller can act without parsing prose.

`
  const zhSurvey =
    warning.length === 0
      ? ''
      : `${warningNames} 比较特殊：默认只是 \`plan\`/\`preflight\` 的稳定警告；当 \`gates.requireFreshSurvey\` 为 \`true\` 时才会
变成合并 blocker。其警告对象带有 \`{code, missionId, depId, readCommit, baseCommit, message}\`，调用方无需解析散文即可处理。

`
  const enReview =
    review.length === 0
      ? ''
      : `The review blockers below (${reviewNames}) exist only when \`review.mode\` is
\`required\`. With \`off\` or \`optional\` no review blocker is produced; \`off\` additionally removes
\`tower_review\` and refuses reviewer spawn.

`
  const zhReview =
    review.length === 0
      ? ''
      : `下列审查 blocker（${reviewNames}）只在 \`review.mode\` 为 \`required\`
时产生。\`off\` 或 \`optional\` 不会产生审查 blocker；\`off\` 还会移除 \`tower_review\` 并拒绝 reviewer spawn。

`

  const en = `# Blockers and failure codes

> Generated by \`npm run docs:generate:blockers\` from \`domain/shapes/blockers.js\`. Do not edit by hand.

\`tower_inspect\` with \`view: "preflight"\` returns \`{ok:false, blockers:[{code, detail}], warnings:[...]}\`. \`tower_merge\` and \`tower_rebase\`
return the same shape for operation failures. Codes are stable; the detail is human-facing. The
tables below define ${total} stable blocker/failure codes.

${enSurvey}${enReview}## Gate blockers (${gate.length})

${table(gate, 'en')}

## Merge failures (${merge.length})

${table(merge, 'en')}

A merge that already landed is **not** a blocker: \`tower_merge\` records it (\`reconciled\`,
\`alreadyLanded\`) or recovers it (\`recoveredFromFailure\`, \`warnings\`).

## ${rebaseHeading}

${table(rebaseRows, 'en')}

\`tower_rebase\` returns \`alreadyMerged: true\` when the branch is already contained in the base; call
\`tower_merge\` to record the landed merge.
`

  const zh = `# blocker 与失败码

> 由 \`npm run docs:generate:blockers\` 从 \`domain/shapes/blockers.js\` 生成，请勿手工编辑。

[English](../../reference/blockers.md) | **简体中文**

\`tower_inspect\` 的 \`view: "preflight"\` 返回 \`{ok:false, blockers:[{code, detail}]}\`。\`tower_merge\` 与 \`tower_rebase\`
在操作失败时返回相同结构。code 稳定；detail 面向人。下表共定义 ${total} 个稳定 blocker/failure code。

${zhSurvey}${zhReview}## 门禁 blocker（${gate.length} 个）

${table(gate, 'zh')}

## 合并失败（${merge.length} 个）

${table(merge, 'zh')}

已经落地的合并不是 blocker：\`tower_merge\` 会记录它（\`reconciled\`、\`alreadyLanded\`），或从失败调用中恢复
（\`recoveredFromFailure\`、\`warnings\`）。

## ${zhRebaseHeading}

${table(rebaseRows, 'zh')}

分支已包含在基线中时，\`tower_rebase\` 返回 \`alreadyMerged: true\`；此时调用 \`tower_merge\` 记录这次
已落地的合并。

稳定的 blocker code 共 ${total} 个（${gate.length} 个门禁 + ${mergeOnly} 个合并失败 + ${rebaseOnly} 个 rebase 专属${sharedFooter}）。
`

  return { en, zh }
}

function main(argv) {
  const rootIndex = argv.indexOf('--root')
  const repoRoot = rootIndex >= 0 ? path.resolve(argv[rootIndex + 1]) : root
  const expected = renderBlockersReference()
  const targets = TARGETS.map((relative) => path.join(repoRoot, relative))
  const check = argv.includes('--check')
  if (check) {
    const stale = []
    for (const [index, target] of targets.entries()) {
      const locale = index === 0 ? 'en' : 'zh'
      const actual = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : ''
      if (actual !== expected[locale]) stale.push(path.relative(repoRoot, target))
    }
    if (stale.length > 0) {
      console.error(`blocker references are stale (${stale.join(', ')}); run npm run docs:generate:blockers`)
      process.exit(1)
    }
  } else {
    for (const [index, target] of targets.entries()) {
      const locale = index === 0 ? 'en' : 'zh'
      fs.mkdirSync(path.dirname(target), { recursive: true })
      fs.writeFileSync(target, expected[locale])
    }
  }
  const { gate, merge, rebase } = sections(BLOCKER_DEFINITIONS)
  const verb = check ? 'in sync' : 'written'
  console.log(
    `blockers reference: ${BLOCKER_DEFINITIONS.length} codes ${verb} (${gate.length} gate, ${merge.length} merge, ${rebase.length} rebase)`,
  )
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main(process.argv.slice(2))
