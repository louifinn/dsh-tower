// First-use Workspace override for the nightly live boot (#47).
//
// The Ubuntu CI runner has no xdg Documents directory. Without one,
// `@deepseek-ai/dsh-api-workspace-controller` cannot resolve its first-use
// workspace (`initializeDefault`), the Web shell parks on the Preview Notice /
// "Choose workspace" state, and the composer never renders. A Windows developer
// machine resolves Documents through PowerShell, which is why the failure was
// CI-only.
//
// The fixture fixes that by pinning the controller's own config key,
// `documentsDirectory`, to an absolute, writable directory under the isolated
// DSH_HOME. The value is applied as a `--patch <overlay>` loader overlay on the
// server spawn, so the profile's shipped layers stay untouched:
//
//   - id: workspace-controller
//     config:
//       documentsDirectory: '<absolute path>'
//
// YAML single quotes are escaped by doubling them, which is what the pinned
// host's YAML loader expects. This module has no Playwright dependency and no
// environment guard, so the offline suite can require it directly.
'use strict'

const fs = require('node:fs')
const path = require('node:path')

/** The environment variable that overrides the default documents directory. */
const DOCUMENTS_DIR_ENV = 'DSH_LIVE_DOCUMENTS_DIR'
/** The default directory name under the isolated DSH_HOME. */
const DOCUMENTS_DIRNAME = 'documents'
/** The loader row the overlay targets (the pinned web profile's id). */
const WORKSPACE_ROW_ID = 'workspace-controller'
/** The overlay file name under the isolated DSH_HOME. */
const OVERLAY_FILENAME = 'workspace-override.patch.yml'

/**
 * Render a YAML single-quoted scalar. Inside single quotes YAML escapes a quote
 * by doubling it; backslashes stay literal, which matters on Windows paths.
 *
 * @param {string} value
 * @returns {string}
 */
function yamlSingleQuote(value) {
  return `'${String(value).replace(/'/g, "''")}'`
}

/**
 * Resolve the documents directory to pin.
 *
 * `DSH_LIVE_DOCUMENTS_DIR` wins when it is set and non-blank; otherwise the
 * default is `<DSH_HOME>/documents`. A relative override is rejected rather than
 * silently resolved against the current directory, because the host validates
 * the config value as a fully qualified path at boot. The isolated DSH_HOME is
 * already proven to be a temp child by `_env.cjs`.
 *
 * @param {{env?: Record<string, string | undefined>, dshHome?: string}} [options]
 * @returns {string} the absolute documents directory
 */
function resolveDocumentsDirectory(options = {}) {
  const env = options.env ?? process.env
  const dshHome = options.dshHome
  if (typeof dshHome !== 'string' || dshHome.trim() === '' || !path.isAbsolute(dshHome)) {
    throw new Error('workspace override: the isolated DSH_HOME must be an absolute directory')
  }
  const override = env[DOCUMENTS_DIR_ENV]
  if (override !== undefined && String(override).trim() !== '') {
    const trimmed = String(override).trim()
    if (!path.isAbsolute(trimmed)) {
      throw new Error(`workspace override: ${DOCUMENTS_DIR_ENV} must be an absolute path, got ${JSON.stringify(trimmed)}`)
    }
    return path.normalize(trimmed)
  }
  return path.join(path.normalize(dshHome), DOCUMENTS_DIRNAME)
}

/**
 * Render the single-row loader overlay that pins the controller's documents
 * directory.
 *
 * @param {string} documentsDirectory an absolute directory
 * @returns {string} YAML text (a top-level array)
 */
function renderOverlay(documentsDirectory) {
  if (typeof documentsDirectory !== 'string' || !path.isAbsolute(documentsDirectory)) {
    throw new Error(`workspace override: documents directory must be an absolute path, got ${JSON.stringify(documentsDirectory)}`)
  }
  return [
    '# Generated by tests/live/nightly.cjs (#47): the first-use Workspace needs a',
    '# writable Documents directory on a CI runner that has no xdg Documents dir.',
    `- id: ${WORKSPACE_ROW_ID}`,
    '  config:',
    `    documentsDirectory: ${yamlSingleQuote(documentsDirectory)}`,
    '',
  ].join('\n')
}

/**
 * Create the writable documents directory and write the overlay under DSH_HOME.
 *
 * Both the directory and the returned paths are absolute. The caller passes
 * `overlayPath` to the host server as `--patch <overlayPath>`.
 *
 * @param {{env?: Record<string, string | undefined>, dshHome?: string}} [options]
 * @returns {{documentsDirectory: string, overlayPath: string}}
 */
function writeWorkspaceOverride(options = {}) {
  const env = options.env ?? process.env
  const dshHome = options.dshHome
  const documentsDirectory = resolveDocumentsDirectory({ env, dshHome })
  fs.mkdirSync(documentsDirectory, { recursive: true })
  const overlayPath = path.join(path.normalize(dshHome), OVERLAY_FILENAME)
  fs.writeFileSync(overlayPath, renderOverlay(documentsDirectory))
  return { documentsDirectory, overlayPath }
}

module.exports = {
  DOCUMENTS_DIR_ENV,
  DOCUMENTS_DIRNAME,
  OVERLAY_FILENAME,
  WORKSPACE_ROW_ID,
  renderOverlay,
  resolveDocumentsDirectory,
  writeWorkspaceOverride,
  yamlSingleQuote,
}
